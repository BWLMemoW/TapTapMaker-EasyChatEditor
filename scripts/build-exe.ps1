    private static void PreloadAssets()
    {
        Assembly asm = Assembly.GetExecutingAssembly();
        foreach (KeyValuePair<string, string> kv in AssetMap)
        {
            if (AssetCache.ContainsKey(kv.Key)) continue;
            using (Stream stream = asm.GetManifestResourceStream(kv.Value))
            {
                if (stream == null) continue;
                using (MemoryStream ms = new MemoryStream())
                {
                    stream.CopyTo(ms);
                    AssetCache[kv.Key] = ms.ToArray();
                }
            }
        }
    }

