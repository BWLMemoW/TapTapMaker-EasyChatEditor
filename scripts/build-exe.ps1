$files = Get-ChildItem -Path $dist -Recurse -File | Sort-Object FullName
$assetMap = New-Object System.Collections.Generic.List[string]
$resourceArgs = New-Object System.Collections.Generic.List[string]
$i = 0
foreach ($file in $files) {
    $rel = $file.FullName.Substring($dist.Length).TrimStart('\', '/').Replace('\', '/')
    $url = '/' + $rel
    $resName = 'ec_' + $i
    $assetMap.Add("            { `"$url`", `"$resName`" },")
    $resourceArgs.Add("/resource:$($file.FullName),$resName")
    $i++
}

