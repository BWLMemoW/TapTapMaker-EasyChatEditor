    private static void HandleClient(TcpClient client)
    {
        try
        {
            using (client)
            using (NetworkStream stream = client.GetStream())
            {
                byte[] buffer = new byte[8192];
                int total = 0;
                byte[] terminator = Encoding.ASCII.GetBytes("\r\n\r\n");
                while (total < buffer.Length)
                {
                    int read = stream.Read(buffer, total, buffer.Length - total);
                    if (read <= 0) break;
                    total += read;
                    if (IndexOf(buffer, total, terminator) >= 0) break;
                }

                int headerEnd = IndexOf(buffer, total, terminator);
                if (headerEnd < 0) return;
                string header = Encoding.ASCII.GetString(buffer, 0, headerEnd);
                string[] lines = header.Replace("\r", "").Split('\n');
                if (lines.Length == 0) return;
                string[] parts = lines[0].Split(' ');
                if (parts.Length < 2) return;

                string method = parts[0];
                string path = parts[1];
                int q = path.IndexOf('?');
                if (q >= 0) path = path.Substring(0, q);

                int contentLength = 0;
                for (int i = 0; i < lines.Length; i++)
                {
                    if (lines[i].StartsWith("Content-Length:"))
                    {
                        int.TryParse(lines[i].Substring("Content-Length:".Length).Trim(), out contentLength);
                    }
                }

                byte[] requestBody = null;
                if (contentLength > 0)
                {
                    int bodyStart = headerEnd + 4;
                    using (MemoryStream ms = new MemoryStream())
                    {
                        int already = total - bodyStart;
                        if (already > 0)
                        {
                            int copy = Math.Min(already, contentLength);
                            ms.Write(buffer, bodyStart, copy);
                        }
                        while (ms.Length < contentLength)
                        {
                            int read = stream.Read(buffer, 0, buffer.Length);
                            if (read <= 0) break;
                            ms.Write(buffer, 0, read);
                        }
                        requestBody = ms.ToArray();
                    }
                }

                // 直接写入已保存的路径（保存按钮使用，不再弹窗）
                // 请求体为纯文本：第一行是目标路径，剩余部分是文件内容。
                // 相比 JSON，避免大文件在 JavaScriptSerializer 反序列化时卡顿。
                if (path == "/__ec_write_file" && method == "POST")
                {
                    string requestText = requestBody == null ? "" : Encoding.UTF8.GetString(requestBody);
                    string targetPath = "";
                    string fileContent = "";
                    int sep = requestText.IndexOf('\n');
                    if (sep >= 0)
                    {
                        targetPath = requestText.Substring(0, sep);
                        fileContent = requestText.Substring(sep + 1);
                    }
                    bool ok = false;
                    if (!string.IsNullOrEmpty(targetPath))
                    {
                        try
                        {
                            File.WriteAllText(targetPath, fileContent ?? "", Encoding.UTF8);
                            ok = true;
                        }
                        catch
                        {
                        }
                    }
                    WriteResponse(stream, "200 OK", "application/json; charset=utf-8", Encoding.UTF8.GetBytes(ok ? "{\"ok\":true}" : "{\"ok\":false}"));
                    return;
                }

                // 从磁盘读取文件内容（重新加载文件使用）
                // 请求体为纯文本：目标路径。
                if (path == "/__ec_read_file" && method == "POST")
                {
                    string targetPath = requestBody == null ? "" : Encoding.UTF8.GetString(requestBody).Trim();
                    string text = "";
                    bool ok = false;
                    if (!string.IsNullOrEmpty(targetPath))
                    {
                        try
                        {
                            if (File.Exists(targetPath))
                            {
                                text = File.ReadAllText(targetPath, Encoding.UTF8);
                                ok = true;
                            }
                        }
                        catch
                        {
                        }
                    }
                    string json = ok
                        ? "{\"ok\":true,\"path\":" + JsonEscape(targetPath) + ",\"text\":" + JsonEscape(text) + "}"
                        : "{\"ok\":false}";
                    WriteResponse(stream, "200 OK", "application/json; charset=utf-8", Encoding.UTF8.GetBytes(json));
                    return;
                }

                // 原生保存剧本：弹出 Windows 保存对话框并写盘
                // 请求体为纯文本：第一行是建议文件名，剩余部分是文件内容。
                if (path == "/__ec_save_file" && method == "POST")
                {
                    string requestText = requestBody == null ? "" : Encoding.UTF8.GetString(requestBody);
                    string suggestedName = "script.txt";
                    string fileContent = "";
                    int sep = requestText.IndexOf('\n');
                    if (sep >= 0)
                    {
                        suggestedName = requestText.Substring(0, sep);
                        fileContent = requestText.Substring(sep + 1);
                    }
                    if (string.IsNullOrEmpty(suggestedName)) suggestedName = "script.txt";
                    WriteResponse(stream, "200 OK", "application/json; charset=utf-8", Encoding.UTF8.GetBytes(SaveFileDialogWithContent(suggestedName, fileContent)));
                    return;
                }

                // 原生文件选择：返回 register.json 的完整路径和内容
                if (path == "/__ec_open_register" && method == "POST")
                {
                    WriteResponse(stream, "200 OK", "application/json; charset=utf-8", Encoding.UTF8.GetBytes(OpenRegisterDialog()));
                    return;
                }

                // 从磁盘重新读取当前保存的 register.json
                if (path == "/__ec_reload_register" && method == "POST")
                {
                    WriteResponse(stream, "200 OK", "application/json; charset=utf-8", Encoding.UTF8.GetBytes(ReloadRegisterFromDisk()));
                    return;
                }

                // 本地设置接口：用于跨启动记住用户选择的 register.json
                if (path == "/__ec_settings")
                {
                    byte[] responseBody;
                    string responseStatus = "200 OK";
                    if (method == "POST" || method == "PUT")
                    {
                        string json = requestBody == null ? "{}" : Encoding.UTF8.GetString(requestBody);
                        WriteSettingsFile(json);
                        responseBody = Encoding.UTF8.GetBytes("{\"ok\":true}");
                    }
                    else
                    {
                        responseBody = Encoding.UTF8.GetBytes(ReadSettingsFile());
                    }
                    WriteResponse(stream, responseStatus, "application/json; charset=utf-8", responseBody);
                    return;
                }

                if (path == "/") path = "/index.html";

                byte[] body = null;
                string contentType = "application/octet-stream";
                if (AssetCache.TryGetValue(path, out body))
                {
                    contentType = GetContentType(path);
                }
                else
                {
                    body = Encoding.UTF8.GetBytes("404 Not Found");
                    contentType = "text/plain; charset=utf-8";
                }

                string status = "200 OK";
                if (path != "/index.html" && !AssetCache.ContainsKey(path))
                {
                    status = "404 Not Found";
                }

                WriteResponse(stream, status, contentType, body);
            }
        }
        catch
        {
        }
    }

    private static void WriteResponse(NetworkStream stream, string status, string contentType, byte[] body)
    {
        StringBuilder sb = new StringBuilder();
        sb.Append("HTTP/1.1 ").Append(status).Append("\r\n");
        sb.Append("Content-Type: ").Append(contentType).Append("\r\n");
        sb.Append("Content-Length: ").Append(body.Length).Append("\r\n");
        sb.Append("Cache-Control: no-cache\r\n");
        sb.Append("Connection: close\r\n\r\n");
        byte[] headerBytes = Encoding.ASCII.GetBytes(sb.ToString());
        stream.Write(headerBytes, 0, headerBytes.Length);
        stream.Write(body, 0, body.Length);
    }

    private static string GetContentType(string path)
    {
        int dot = path.LastIndexOf('.');
        if (dot >= 0)
        {
            string ext = path.Substring(dot).ToLowerInvariant();
            string mime;
            if (MimeMap.TryGetValue(ext, out mime)) return mime;
        }
        return "application/octet-stream";
    }

    private static int IndexOf(byte[] haystack, int length, byte[] needle)
    {
        if (needle.Length == 0) return 0;
        for (int i = 0; i <= length - needle.Length; i++)
        {
            bool found = true;
            for (int j = 0; j < needle.Length; j++)
            {
                if (haystack[i + j] != needle[j])
                {
                    found = false;
                    break;
                }
            }
            if (found) return i;
        }
        return -1;
    }
}
